<?php

namespace mttzzz\AmoClient\Traits;

/**
 * Сортировка для сущностей, у которых она подтверждена: leads, contacts,
 * companies.
 *
 * ПОДДЕРЖКА СОРТИРОВКИ У АМО НЕ ЕДИНООБРАЗНА МЕЖДУ РОУТАМИ — это главное, что
 * нужно знать перед тем, как подключать трейт к новой модели. У примечаний
 * `order[updated_at]` работает (§8.7), у задач тот же параметр игнорируется
 * целиком: три противоположных значения дают побайтово одну и ту же выдачу
 * (§8.8). Оба роута отвечают на любую просьбу одинаково успешно, поэтому
 * **200 в ответ не означает, что параметр учтён**, и проверить это можно
 * только по данным.
 *
 * Отсюда правило: не подключать трейт целиком ради одного метода. Он приносит
 * три поля разом, и каждое неподтверждённое поле — не запас на будущее, а
 * метод, который молча ничего не делает. Лучше отсутствие возможности, чем её
 * видимость.
 *
 * Допустимые поля по официальному справочнику (§9): задачи — `created_at`,
 * `complete_till`, `id`, и `updated_at` там НЕ значится (документация была
 * права, неверным оказалось наше допущение по аналогии с примечаниями);
 * примечания — `updated_at`, `id`. Для leads/contacts/companies все три поля
 * трейта подтверждены сьютом `OrderTraitTest`, который сверяет фактический
 * порядок выдачи, а не форму запроса.
 *
 * ПОЧЕМУ ИМЯ МЕТОДА, А НЕ СТРОКОВЫЙ ПАРАМЕТР — и почему мы намеренно расходимся
 * тут с эталонной реализацией вендора. Официальный SDK амо делает так:
 * `Filters/Traits/OrderTrait::setOrder(string $field, string $direction)`, БЕЗ
 * какой-либо валидации поля — любая строка уходит насквозь, причём
 * `TasksFilter` подключает этот трейт ровно так же, как `NotesFilter`. То есть
 * официальная библиотека позволяет попросить у задач сортировку по
 * `updated_at`, амо отвечает 200 несортированной выдачей, и промаха не замечает
 * НИКТО: ни SDK, ни API, ни разработчик. У нас недопустимое поле непредставимо
 * — его нечем выразить, метода с таким именем просто нет.
 *
 * Поэтому это не стилистика и не кандидат на «упрощение до setOrder(string,
 * string) как у вендора»: такое упрощение вернёт ровно тот дефект, ради
 * которого расхождение и введено.
 *
 * Каждый вызов замещает предыдущий; причина — в `AbstractModel::orderBy()`.
 */
trait OrderTrait
{
    public function orderByCreatedAtAsc(): self
    {
        return $this->orderBy('created_at', 'asc');
    }

    public function orderByCreatedAtDesc(): self
    {
        return $this->orderBy('created_at', 'desc');
    }

    public function orderByUpdatedAtAsc(): self
    {
        return $this->orderBy('updated_at', 'asc');
    }

    public function orderByUpdatedAtDesc(): self
    {
        return $this->orderBy('updated_at', 'desc');
    }

    public function orderByIdAsc(): self
    {
        return $this->orderBy('id', 'asc');
    }

    public function orderByIdDesc(): self
    {
        return $this->orderBy('id', 'desc');
    }
}
